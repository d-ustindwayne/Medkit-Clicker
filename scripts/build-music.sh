#!/usr/bin/env sh
# Encodes your music library for the database. The app no longer ships the songs: Jasmine's code
# downloads them from the server (see db/schema.sql and server/index.ts).
# Source:  src/audio/music/<playlist>/track_N.mp3   (your full library, gitignored)
# Output:  src/audio/encoded/<playlist>/track_N.m4a (gitignored), uploaded by `bun run db:setup`.
# With BUNDLE=1 the songs are also bundled into the app (src/audio/bundle) for offline testing;
# otherwise src/audio/bundle/index.ts is written empty so no music ships in the APK.
# AAC at 64 kbps plays natively on Android and iOS; the whole library comes to ~110 MB.
# Requires ffmpeg. Usage: bun run music   (or: BUNDLE=1 bun run music)
set -e
SRC=src/audio/music
ENC=src/audio/encoded
OUT=src/audio/bundle
BITRATE=64k

mkdir -p "$ENC"
for dir in "$SRC"/*/; do
  name=$(basename "$dir")
  mkdir -p "$ENC/$name"
  for n in $(ls "$dir" | sed -n 's/^track_\([0-9]*\)\.mp3$/\1/p' | sort -n); do
    out="$ENC/$name/track_$n.m4a"
    [ -f "$out" ] && continue
    ffmpeg -loglevel error -y -i "$dir/track_$n.mp3" -vn -map_metadata -1 -ac 2 -c:a aac -b:a $BITRATE -movflags +faststart "$out"
    echo "encoded $out"
  done
done

rm -rf "$OUT"
mkdir -p "$OUT"
INDEX="$OUT/index.ts"
printf '// Generated by `bun run music`. Do not edit.\nexport const TRACKS: Record<string, number[]> = {\n' > "$INDEX"
if [ "$BUNDLE" = "1" ]; then
  for dir in "$ENC"/*/; do
    name=$(basename "$dir")
    mkdir -p "$OUT/$name"
    printf '  "%s": [\n' "$name" >> "$INDEX"
    for n in $(ls "$dir" | sed -n 's/^track_\([0-9]*\)\.m4a$/\1/p' | sort -n); do
      cp "$dir/track_$n.m4a" "$OUT/$name/track_$n.m4a"
      printf '    require("./%s/track_%s.m4a"),\n' "$name" "$n" >> "$INDEX"
    done
    printf '  ],\n' >> "$INDEX"
  done
  echo "bundled into the app:"; du -sh "$OUT"
else
  echo "no songs bundled into the app (they download from the server after the code)"
fi
printf '};\n' >> "$INDEX"
du -sh "$ENC"
