#!/usr/bin/env sh
# Builds the compressed music bundle the app ships with: every track of every playlist.
# Source:  src/audio/music/<playlist>/track_N.mp3   (your full library, gitignored)
# Output:  src/audio/bundle/<playlist>/track_N.m4a  (gitignored) plus src/audio/bundle/index.ts,
#          the generated track list that src/constants/playlists.ts reads.
# AAC at 64 kbps plays natively on Android and iOS; the whole library comes to ~110 MB.
# Requires ffmpeg. Usage: bun run music
set -e
SRC=src/audio/music
OUT=src/audio/bundle
BITRATE=64k

rm -rf "$OUT"
mkdir -p "$OUT"
INDEX="$OUT/index.ts"
printf '// Generated by `bun run music`. Do not edit.\nexport const TRACKS: Record<string, number[]> = {\n' > "$INDEX"
for dir in "$SRC"/*/; do
  name=$(basename "$dir")
  mkdir -p "$OUT/$name"
  printf '  "%s": [\n' "$name" >> "$INDEX"
  # numeric order: track_1, track_2, ... track_10
  for n in $(ls "$dir" | sed -n 's/^track_\([0-9]*\)\.mp3$/\1/p' | sort -n); do
    ffmpeg -loglevel error -y -i "$dir/track_$n.mp3" -vn -map_metadata -1 -ac 2 -c:a aac -b:a $BITRATE -movflags +faststart "$OUT/$name/track_$n.m4a"
    printf '    require("./%s/track_%s.m4a"),\n' "$name" "$n" >> "$INDEX"
    echo "built $OUT/$name/track_$n.m4a"
  done
  printf '  ],\n' >> "$INDEX"
done
printf '};\n' >> "$INDEX"
du -sh "$OUT"
