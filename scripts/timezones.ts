// Builds src/constants/timezones.ts and the website's copy (website/src/lib/timezones.ts): a rough
// place (latitude, longitude) for every time zone, from the IANA tz database (zone1970.tab gives each zone's main city; backward maps old names to them).
// The hospital uses it to work out sunrise and sunset without asking for the player's location.
// Run: bun scripts/timezones.ts
const BASE = "https://raw.githubusercontent.com/eggert/tz/main/";
const get = async (name: string) => {
  const res = await fetch(BASE + name);
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  return res.text();
};

/** "+DDMM", "+DDMMSS", "+DDDMM" or "+DDDMMSS" to degrees. */
const degrees = (s: string, degDigits: number) => {
  const sign = s[0] === "-" ? -1 : 1;
  const d = Number(s.slice(1, 1 + degDigits)), m = Number(s.slice(1 + degDigits, 3 + degDigits)), sec = Number(s.slice(3 + degDigits) || 0);
  return sign * (d + m / 60 + sec / 3600);
};

const places = new Map<string, [number, number]>();
for (const line of (await get("zone1970.tab")).split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [, coords, zone] = line.split("\t");
  const m = coords.match(/^([+-]\d+)([+-]\d+)$/);
  if (!m) throw new Error(`Bad coordinates: ${line}`);
  places.set(zone, [Math.round(degrees(m[1], 2) * 10) / 10, Math.round(degrees(m[2], 3) * 10) / 10]);
}
for (const line of (await get("backward")).split("\n")) {
  const [kind, target, alias] = line.split(/\s+/);
  if (kind === "Link" && places.has(target) && !places.has(alias)) places.set(alias, places.get(target)!);
}

const body = [...places].sort(([a], [b]) => a.localeCompare(b)).map(([zone, [lat, lng]]) => `  "${zone}": [${lat}, ${lng}],`);
const file = `// Generated by scripts/timezones.ts from the IANA tz database. Don't edit by hand.
/** Each time zone's main city as [latitude, longitude], rounded to 0.1 degree. */
export const TIMEZONE_PLACES: Record<string, [number, number]> = {
${body.join("\n")}
};
`;
for (const path of ["src/constants/timezones.ts", "website/src/lib/timezones.ts"]) await Bun.write(path, file);
console.log(`${places.size} time zones`);
