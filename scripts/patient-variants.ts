// Patient look variants, like the cars: each ward patient's sprite recoloured with a different skin
// tone and clothes colour, so the same patient doesn't always look the same.
// Run: bun scripts/patient-variants.ts  (writes src/imgs/characters/variants/ and
// src/constants/patient-variants.ts). The originals in src/imgs/characters are untouched.
import { PNG } from "pngjs";
import fs from "node:fs";

const SRC = "src/imgs/characters";
const OUT = `${SRC}/variants`;
const PATIENTS = ["01_red_hair_woman", "02_islander_man_sick", "03_blonde_woman", "04_old_man_sick", "05_chinese_woman_sick", "06_teacher", "07_kid_gamer", "08_teen_girl", "09_dad_sick", "10_young_man_sick"];

type HSV = [number, number, number];
const toHsv = (r: number, g: number, b: number): HSV => {
  const mx = Math.max(r, g, b) / 255, mn = Math.min(r, g, b) / 255, d = mx - mn;
  let h = 0;
  if (d) h = mx === r / 255 ? ((g - b) / 255 / d) % 6 : mx === g / 255 ? (b - r) / 255 / d + 2 : (r - g) / 255 / d + 4;
  return [((h * 60) + 360) % 360, mx ? d / mx : 0, mx];
};
const toRgb = ([h, s, v]: HSV) => {
  const c = v * s, x = c * (1 - Math.abs(((h / 60) % 2) - 1)), m = v - c;
  const [r, g, b] = h < 60 ? [c, x, 0] : h < 120 ? [x, c, 0] : h < 180 ? [0, c, x] : h < 240 ? [0, x, c] : h < 300 ? [x, 0, c] : [c, 0, x];
  return [r + m, g + m, b + m].map((n) => Math.round(Math.min(1, Math.max(0, n)) * 255));
};

/** Skin: warm, not too saturated, not dark (dark browns are hair). */
const isSkin = ([h, s, v]: HSV) => h >= 12 && h <= 36 && s >= 0.12 && s <= 0.6 && v >= 0.5;
/** Clothes: clearly coloured and not skin (greys, whites and near-blacks stay). */
const isCloth = (hsv: HSV) => !isSkin(hsv) && hsv[1] >= 0.28 && hsv[2] >= 0.22 && !(hsv[0] >= 10 && hsv[0] <= 40 && hsv[2] < 0.45);

/** Skin tones as how much lighter/darker and warmer than the original: [value x, saturation x, hue shift]. */
const SKINS: [number, number, number][] = [
  [1, 1, 0],
  [1.07, 0.75, 2],
  [0.8, 1.2, -2],
  [0.6, 1.25, -4],
  [0.45, 1.15, -6],
];
/** Clothes hue turns, in degrees. */
const CLOTHES = [0, 110, 200, 290];

fs.mkdirSync(OUT, { recursive: true });
const list: string[] = [];
for (const id of PATIENTS) {
  const png = PNG.sync.read(fs.readFileSync(`${SRC}/${id}.png`));
  // Hair: colours found mostly on the head (the top 35% of the figure) keep their colour, so only
  // clothes change. Long hair that reaches the shoulders still counts, as most of it is up top.
  let top = png.height, bottom = 0;
  for (let i = 0; i < png.data.length; i += 4) {
    if (png.data[i + 3] === 0) continue;
    const y = Math.floor(i / 4 / png.width);
    top = Math.min(top, y);
    bottom = Math.max(bottom, y);
  }
  const headLine = top + (bottom - top) * 0.35;
  const seen = new Map<number, { head: number; all: number }>();
  for (let i = 0; i < png.data.length; i += 4) {
    if (png.data[i + 3] === 0) continue;
    const key = (png.data[i] << 16) | (png.data[i + 1] << 8) | png.data[i + 2];
    const c = seen.get(key) ?? { head: 0, all: 0 };
    c.all++;
    if (Math.floor(i / 4 / png.width) < headLine) c.head++;
    seen.set(key, c);
  }
  const onHead = (key: number) => {
    const c = seen.get(key)!;
    return c.head / c.all > 0.5;
  };
  // Six looks per patient (the original is the first), picked so each skin tone and clothes colour shows up.
  const looks: [number, number][] = [[0, 0], [1, 1], [2, 2], [3, 3], [4, 1], [2, 3]];
  looks.forEach(([si, ci], k) => {
    if (k === 0) return;
    const out = new PNG({ width: png.width, height: png.height });
    png.data.copy(out.data);
    const [vx, sx, hs] = SKINS[si];
    for (let i = 0; i < out.data.length; i += 4) {
      if (out.data[i + 3] === 0) continue;
      const hsv = toHsv(out.data[i], out.data[i + 1], out.data[i + 2]);
      let next: HSV | null = null;
      if (isSkin(hsv)) next = [(hsv[0] + hs + 360) % 360, Math.min(1, hsv[1] * sx), Math.min(1, hsv[2] * vx)];
      else if (isCloth(hsv) && CLOTHES[ci] && !onHead((out.data[i] << 16) | (out.data[i + 1] << 8) | out.data[i + 2])) next = [(hsv[0] + CLOTHES[ci]) % 360, hsv[1], hsv[2]];
      if (!next) continue;
      const [r, g, b] = toRgb(next);
      out.data[i] = r;
      out.data[i + 1] = g;
      out.data[i + 2] = b;
    }
    const name = `${id}_v${k}.png`;
    fs.writeFileSync(`${OUT}/${name}`, PNG.sync.write(out));
    list.push(`  "${id}_v${k}": require("@/imgs/characters/variants/${name}"),`);
  });
}
fs.writeFileSync(
  "src/constants/patient-variants.ts",
  `// Generated by scripts/patient-variants.ts: recoloured looks for the ward patients (skin tone and clothes).
import type { ImageSourcePropType } from "react-native";

export const PATIENT_VARIANTS: Record<string, ImageSourcePropType> = {
${list.join("\n")}
};

/** The looks for one patient's sprite (file name without .png): the original plus its variants. */
export const VARIANTS_PER_PATIENT = 5;
`,
);
