// Writes src/constants/sticker-data.ts: every sticker PNG as base64, so the app can save a sticker
// without reading its bundled image (release builds keep images inside the APK, not as files).
// Run after changing a sticker: bun scripts/sticker-data.ts
import { readdirSync, readFileSync, writeFileSync } from "fs";

const dir = `${import.meta.dir}/../src/imgs/stickers`;
const lines = readdirSync(dir)
  .filter((f) => f.endsWith(".png"))
  .sort()
  .map((f) => `  ${f.replace(/\.png$/, "")}: "${readFileSync(`${dir}/${f}`).toString("base64")}",`);
writeFileSync(
  `${import.meta.dir}/../src/constants/sticker-data.ts`,
  `// Generated by scripts/sticker-data.ts from src/imgs/stickers. Do not edit.\nexport const STICKER_PNG: Record<string, string> = {\n${lines.join("\n")}\n};\n`,
);
console.log(`${lines.length} stickers`);
